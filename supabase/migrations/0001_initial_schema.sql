-- RETRO Store initial schema
-- Run in Supabase SQL Editor. This migration intentionally creates no owner account.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('owner', 'customer')),
  created_at timestamptz not null default now()
);

-- Create a customer profile for each newly registered Auth user.
-- The owner role is assigned manually by a trusted project administrator.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, role)
  values (new.id, 'customer')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_retro_store on auth.users;
create trigger on_auth_user_created_retro_store
  after insert on auth.users
  for each row execute procedure public.handle_new_auth_user();

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  description text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  slug text not null unique,
  summary text,
  description text,
  price_iqd bigint not null check (price_iqd >= 0),
  compare_at_price_iqd bigint check (compare_at_price_iqd is null or compare_at_price_iqd >= price_iqd),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  image_urls text[] not null default '{}',
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated always as identity unique,
  customer_name text not null,
  phone text not null,
  city text not null,
  address text not null,
  notes text,
  subtotal_iqd bigint not null check (subtotal_iqd >= 0),
  delivery_fee_iqd bigint not null default 0 check (delivery_fee_iqd >= 0),
  total_iqd bigint not null check (total_iqd = subtotal_iqd + delivery_fee_iqd),
  status text not null default 'pending' check (status in ('pending','confirmed','preparing','shipped','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price_iqd bigint not null check (unit_price_iqd >= 0),
  quantity integer not null check (quantity > 0),
  line_total_iqd bigint not null check (line_total_iqd = unit_price_iqd * quantity)
);

create index if not exists products_active_category_idx on public.products(is_active, category_id);
create index if not exists products_slug_idx on public.products(slug);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx on public.orders(status);

create or replace function public.is_store_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'owner'
  );
$$;

revoke all on function public.is_store_owner() from public;
grant execute on function public.is_store_owner() to authenticated;

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Public reads active categories" on public.categories;
create policy "Public reads active categories" on public.categories for select to anon, authenticated using (is_active or public.is_store_owner());
drop policy if exists "Owner manages categories" on public.categories;
create policy "Owner manages categories" on public.categories for all to authenticated using (public.is_store_owner()) with check (public.is_store_owner());

drop policy if exists "Public reads active products" on public.products;
create policy "Public reads active products" on public.products for select to anon, authenticated using (is_active or public.is_store_owner());
drop policy if exists "Owner manages products" on public.products;
create policy "Owner manages products" on public.products for all to authenticated using (public.is_store_owner()) with check (public.is_store_owner());

drop policy if exists "Owner reads profiles" on public.profiles;
create policy "Owner reads profiles" on public.profiles for select to authenticated using (id = (select auth.uid()) or public.is_store_owner());
drop policy if exists "Owner updates profiles" on public.profiles;
create policy "Owner updates profiles" on public.profiles for update to authenticated using (public.is_store_owner()) with check (public.is_store_owner());

-- No anonymous INSERT policy on orders/order_items. Public checkout writes use the RPC below.

create or replace function public.place_store_order(
  p_customer_name text,
  p_phone text,
  p_city text,
  p_address text,
  p_notes text,
  p_items jsonb,
  p_delivery_fee_iqd bigint default 0
)
returns table(order_id uuid, order_number bigint, total_iqd bigint)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid := gen_random_uuid();
  v_subtotal bigint := 0;
  v_total bigint := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if length(trim(coalesce(p_customer_name,''))) < 2
     or length(trim(coalesce(p_customer_name,''))) > 100
     or length(trim(coalesce(p_phone,''))) < 7
     or length(trim(coalesce(p_phone,''))) > 30
     or length(trim(coalesce(p_city,''))) < 2
     or length(trim(coalesce(p_city,''))) > 100
     or length(trim(coalesce(p_address,''))) < 5
     or length(trim(coalesce(p_address,''))) > 500
     or length(coalesce(p_notes,'')) > 1000 then
    raise exception 'بيانات العميل غير مكتملة أو طويلة جداً';
  end if;

  if p_delivery_fee_iqd is null or p_delivery_fee_iqd < 0
     or p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'بيانات الطلب غير صالحة';
  end if;

  -- Reject repeated product IDs so each stock unit is validated and deducted once.
  if exists (
    select 1
    from jsonb_array_elements(p_items) as item(value)
    group by item.value->>'product_id'
    having count(*) > 1
  ) then
    raise exception 'لا تكرر المنتج نفسه في عناصر الطلب';
  end if;

  -- Lock and validate each product; price always comes from the database.
  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object'
       or coalesce(v_item->>'product_id','') = ''
       or coalesce(v_item->>'quantity','') !~ '^[0-9]+$' then
      raise exception 'عنصر طلب غير صالح';
    end if;

    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 or v_qty > 20 then raise exception 'كمية غير صالحة'; end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::uuid and is_active = true
    for update;

    if not found then raise exception 'أحد المنتجات غير متاح'; end if;
    if v_product.stock_quantity < v_qty then raise exception 'المخزون غير كافٍ للمنتج: %', v_product.name; end if;
    v_subtotal := v_subtotal + (v_product.price_iqd * v_qty);
  end loop;

  v_total := v_subtotal + p_delivery_fee_iqd;

  insert into public.orders (
    id, customer_name, phone, city, address, notes,
    subtotal_iqd, delivery_fee_iqd, total_iqd
  ) values (
    v_order_id, trim(p_customer_name), trim(p_phone), trim(p_city),
    trim(p_address), nullif(trim(coalesce(p_notes,'')), ''),
    v_subtotal, p_delivery_fee_iqd, v_total
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products
    where id = (v_item->>'product_id')::uuid and is_active = true
    for update;

    update public.products
      set stock_quantity = stock_quantity - v_qty,
          updated_at = now()
      where id = v_product.id and stock_quantity >= v_qty;

    if not found then raise exception 'تغير المخزون أثناء إتمام الطلب'; end if;

    insert into public.order_items (
      order_id, product_id, product_name, unit_price_iqd, quantity, line_total_iqd
    ) values (
      v_order_id, v_product.id, v_product.name, v_product.price_iqd,
      v_qty, v_product.price_iqd * v_qty
    );
  end loop;

  return query
    select o.id, o.order_number, o.total_iqd
    from public.orders o where o.id = v_order_id;
end;
$$;

revoke all on function public.place_store_order(text,text,text,text,text,jsonb,bigint) from public;
grant execute on function public.place_store_order(text,text,text,text,text,jsonb,bigint) to anon, authenticated;

